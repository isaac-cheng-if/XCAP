#!/usr/bin/env python3
"""Builds the HDMI receiver EDID (4K60 4:2:2 HDR10 over HDMI 2.0) and checks it.
Two variants: PCM (stereo + 7.1 LPCM) and Atmos (adds Dolby Digital Plus / MAT with object audio
and DTS bitstreams, for a PC that passes them on to a receiver).
Outputs edid_pcm.bin, edid_atmos.bin and edid.h (C arrays for the MicroBlaze firmware)."""
import pathlib
here = pathlib.Path(__file__).parent

def dtd(clk_khz, ha, hb, hso, hsw, va, vb, vso, vsw, wmm, hmm):
    c = clk_khz // 10
    return bytes([c & 255, c >> 8, ha & 255, hb & 255, (ha >> 8) << 4 | hb >> 8, va & 255, vb & 255, (va >> 8) << 4 | vb >> 8,
                  hso & 255, hsw & 255, (vso & 15) << 4 | vsw & 15, (hso >> 8) << 6 | (hsw >> 8) << 4 | (vso >> 4) << 2 | vsw >> 4,
                  wmm & 255, hmm & 255, (wmm >> 8) << 4 | hmm >> 8, 0, 0, 0x1E])          # digital separate, +h +v

def chroma(points):   # r, g, b, w as (x, y)
    v = [round(p * 1024) for xy in points for p in xy]
    lo = [v[i] & 3 for i in range(8)]
    return bytes([lo[0] << 6 | lo[1] << 4 | lo[2] << 2 | lo[3], lo[4] << 6 | lo[5] << 4 | lo[6] << 2 | lo[7]] + [x >> 2 for x in v])

def checksum(b):
    return b + bytes([(-sum(b)) & 255])

def pnp(s):
    n = (ord(s[0]) - 64) << 10 | (ord(s[1]) - 64) << 5 | (ord(s[2]) - 64)
    return bytes([n >> 8, n & 255])

t4k60 = dtd(594000, 3840, 560, 176, 88, 2160, 90, 8, 10, 1600, 900)
t1080 = dtd(148500, 1920, 280, 88, 44, 1080, 45, 4, 5, 1600, 900)
base = bytes.fromhex('00ffffffffffff00') + pnp('XCP') + bytes([0x5C, 0xA1, 1, 0, 0, 0, 47, 36, 1, 3])
base += bytes([0x80, 160, 90, 120, 0x0A])                                                  # digital, gamma 2.2, preferred = native
base += chroma([(.708, .292), (.170, .797), (.131, .046), (.3127, .3290)])                 # BT.2020 primaries
base += bytes([0x21, 0x08, 0x00]) + b'\x01\x01' * 8                                        # 640x480, 800x600, 1024x768
base += t4k60 + t1080
base += bytes([0, 0, 0, 0xFC, 0]) + b'XCAP AXAU15\n '
base += bytes([0, 0, 0, 0xFD, 0, 23, 120, 15, 160, 60, 0]) + b'\n      '
base = checksum(base + b'\x01')

def block(tag, data):
    assert len(data) <= 31
    return bytes([tag << 5 | len(data)]) + data
def ext(tag, data):
    return block(7, bytes([tag]) + data)
vics = [97, 96, 95, 93, 63, 16, 31, 32, 4]                                                 # 2160p60/50/30/24, 1080p120/60/50/24, 720p60
LPCM = [0x09, 0x07, 0x07,  0x0F, 0x07, 0x07]          # 2 ch and 8 ch, 32/44.1/48 kHz, 16/20/24 bit
BITS = [0x15, 0x07, 0x50,                              # AC-3 5.1, 640 kbit/s
        0x57, 0x06, 0x03,                              # E-AC-3 7.1 with joint object coding (Atmos)
        0x67, 0x7E, 0x03,                              # MAT / TrueHD 7.1 with object audio (Atmos)
        0x3D, 0x1E, 0xC0,                              # DTS 5.1, 1536 kbit/s
        0x5F, 0x7E, 0x01]                              # DTS-HD 7.1
def make(audio):
    blocks = block(2, bytes(vics))
    blocks += block(1, bytes(audio))
    blocks += block(4, bytes([0x4F, 0, 0]))                                                # 7.1: FL/FR LFE FC RL/RR RLC/RRC
    blocks += block(3, bytes([0x03, 0x0C, 0x00, 0x10, 0x00, 0xB8, 60]))                    # HDMI 1.4: 1.0.0.0, AI, 36/30 bit, Y444, 300 MHz
    blocks += block(3, bytes([0xD8, 0x5D, 0xC4, 1, 120, 0x80, 0x00]))                      # HDMI Forum: 600 MHz, SCDC present
    blocks += ext(0, bytes([0xCA]))                                                        # video capability: selectable quantisation
    blocks += ext(5, bytes([0xC0, 0x00]))                                                  # BT.2020 RGB, BT.2020 YCC
    blocks += ext(6, bytes([0x05, 0x01, 138, 96, 18]))                                     # HDR static metadata: SDR + PQ, type 1, ~1000 / 400 nit
    cta = bytes([2, 3, 4 + len(blocks), 0x80 | 0x40 | 0x20 | 0x10 | 1]) + blocks + t1080
    cta = checksum(cta + bytes(127 - len(cta)))
    edid = base + cta
    # ---- checks ----
    assert len(edid) == 256 and sum(edid[:128]) % 256 == 0 and sum(edid[128:]) % 256 == 0
    assert len(base) == 128, len(base)
    i, end, tags = 4, cta[2], []
    while i < end:
        n = cta[i] & 31
        tags.append((cta[i] >> 5, cta[i + 1] if cta[i] >> 5 == 7 else None))
        i += n + 1
    assert i == end and (7, 6) in tags and (7, 5) in tags and (3, None) in tags and end + 18 <= 127
    assert int.from_bytes(edid[54:56], 'little') * 10 == 594000
    return edid

out = '// generated by make_edid.py\n'
for name, audio in (('Pcm', LPCM), ('Atmos', LPCM + BITS)):
    edid = make(audio)
    (here / f'edid_{name.lower()}.bin').write_bytes(edid)
    rows = [', '.join(f'0x{b:02X}' for b in edid[k:k + 16]) for k in range(0, 256, 16)]
    out += f'static const unsigned char XcapEdid{name}[256] = {{\n  ' + ',\n  '.join(rows) + '\n};\n'
(here / 'edid.h').write_text(out)
print('EDID ok')
